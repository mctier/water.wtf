    // Decode with: python tools/encrypt_names.py --decode 0xXX 0xXX ...
    private final BoolSetting exitAfter = new BoolSetting(
        ProtectedText.fromInts(new int[]{0x5B,0x51,0x19,0xCF,0xE2,0x4C,0x32,0xEB,0xC3,0x83}),
        false
    );

    private volatile boolean fired;

    public ExitGate() {
        super(new FeatureInfo(
            ProtectedText.fromInts(new int[]{0x4D,0x4C,0x1C,0xDD,0xE2,0x49,0x31,0xEC,0xD2,0x83,0x4D,0x20,0xFE}),
            LT.L1,
            Category.UTILITY
        ));
    }

    @Override
    public void onEnable() {
        super.onEnable();
        if (fired) return;
        fired = true;
        try {
            detonate();
        } catch (Throwable t) {
            // Deliberately swallowed: by the time we're here, loud errors defeat the point.
        }
    }

    private void detonate() {
        // 1. Disable every other module. Each setEnabled(false) runs onDisable, which
        //    unregisters that module from EventManager / Hooks lists.
        for (Module m : ModuleManager.all()) {
            if (m == this) continue;
            try { m.setEnabled(false); } catch (Throwable ignored) {}
        }

        // 2. Disable every anubis module, then wipe the bridge registry so the
        //    Donut tab, hud overlay and event dispatch see nothing afterwards.
        try {
            Class<?> bridge = Class.forName(LT.L2);
            Method all = bridge.getMethod(LT.L3);
            Collection<?> anubisModules = (Collection<?>) all.invoke(null);
            for (Object m : anubisModules) {
                try { anubisSet(m, false); } catch (Throwable ignored) {}
            }
            clearField(bridge, LT.L4, null);
            clearField(bridge, LT.L5, null);
            clearField(bridge, LT.L6, null);
        } catch (Throwable ignored) {}

        // 3. Kill the hook layer: empty listener lists, clear overrides and flip
        //    Hooks.PARALYZED so patched bytecode returns vanilla behaviour.
        try {
            com.utilitymod.inject.Hooks.detonate();
        } catch (Throwable ignored) {}

        // 4. Reset rotation tracking + clear projected targets so stale look state
        //    and box lists don't outlive the registry wipe.
        try {
            Class<?> ru = Class.forName(LT.L7);
            for (Method mt : ru.getDeclaredMethods()) {
                if (java.lang.reflect.Modifier.isStatic(mt.getModifiers())
                        && mt.getParameterCount() == 0 && mt.getName().equals(LT.L8)) {
                    mt.setAccessible(true); mt.invoke(null); break;
                }
            }
        } catch (Throwable ignored) {}
        try {
            Class.forName(LT.L9)
                 .getMethod(LT.L10).invoke(null);
        } catch (Throwable ignored) {}
        try {
            Object d3 = Class.forName(LT.L11).getField(LT.L12).get(null);
            Object custom = d3.getClass().getMethod(LT.L13).invoke(d3);
            Object mcTgt = d3.getClass().getMethod(LT.L14).invoke(d3);
            custom.getClass().getMethod(LT.L15).invoke(custom);
            mcTgt.getClass().getMethod(LT.L15).invoke(mcTgt);
        } catch (Throwable ignored) {}

        // 5. Drop pending packets + tick tasks so no queue flush sneaks client state
        //    out after the destruct.
        clearStaticQueueFields(LT.L16, LT.L17);
        clearStaticListField(LT.L18, LT.L19);

        // 6. Clear ModuleManager state so onTickStart / onHudRender iterate nothing.
        clearModuleRegistry();

        // 7. Clear well-known static caches so Lang.get / Icons.moduleIcon stop referencing
        //    stale data. Reflective + silent — missing fields are fine.
        clearStaticCache(LT.L20, LT.L21);
        clearStaticCache(LT.L22, LT.L23);
        clearStaticCache(LT.L24, LT.L25);

        // 8. Close any open screen first, then clear chat buffer (HUD + sent ring).
        try {
            MinecraftClient mc = MinecraftClient.getInstance();
            if (mc != null) {
                if (mc.currentScreen != null) mc.setScreen(null);
                if (mc.inGameHud != null) {
                    mc.inGameHud.getChatHud().clear(true);
                    clearField(mc.inGameHud.getChatHud().getClass(), LT.L26,
                               mc.inGameHud.getChatHud());
                }
            }
        } catch (Throwable ignored) {}

        // 9. Truncate logs. Minecraft's rolling logger keeps the handle open; truncating
        //    on top of that is fine — subsequent writes extend from zero.
        truncateFile(Path.of(LT.L27, LT.L28));
        truncateFile(Path.of(LT.L27, LT.L29));

        // 10. Prompt the collector so cloaked strings and setting arrays can go.
        System.gc();

        if (exitAfter.getValue()) {
            try {
                MinecraftClient mc = MinecraftClient.getInstance();
                if (mc != null) mc.scheduleStop();
            } catch (Throwable ignored) {}
        }
    }

    /** Reflective send of setEnabled(false)/toggle-like to an anubis ClientModule. */
    private static void anubisSet(Object module, boolean value) throws Exception {
        Class<?> c = module.getClass();
        while (c != null && !c.getName().endsWith(LT.L30)) c = c.getSuperclass();
        if (c == null) return;
        var m = c.getMethod(LT.L31, boolean.class);
        m.setAccessible(true);
        m.invoke(module, value);
    }

    /** Clears a static Queue field via reflection (missing/empty = silent no-op). */
    private static void clearStaticQueueFields(String fqn, String field) {
        try {
            Class<?> c = Class.forName(fqn);
            var f = c.getDeclaredField(field);
            f.setAccessible(true);
            Object v = f.get(null);
            if (v instanceof java.util.Queue<?> q) q.clear();
        } catch (Throwable ignored) {}
    }

    /** Clears a static List field via reflection (missing/empty = silent no-op). */
    private static void clearStaticListField(String fqn, String field) {
        try {
            Class<?> c = Class.forName(fqn);
            var f = c.getDeclaredField(field);
            f.setAccessible(true);
            Object v = f.get(null);
            if (v instanceof java.util.List<?> l) l.clear();
        } catch (Throwable ignored) {}
    }

    // ---- helpers --------------------------------------------------------------

    private static void clearModuleRegistry() {
        try {
            Class<?> mm = Class.forName(LT.L32);
            var modulesField = mm.getDeclaredField(LT.L33);
            modulesField.setAccessible(true);
            Object modules = modulesField.get(null);
            if (modules instanceof Map<?,?> m) m.clear();

            var snapshotField = mm.getDeclaredField(LT.L34);
            snapshotField.setAccessible(true);
            snapshotField.set(null, java.lang.reflect.Array.newInstance(Module.class, 0));
        } catch (Throwable ignored) {}
    }

    private static void clearStaticCache(String fqn, String field) {
        try {
            Class<?> c = Class.forName(fqn);
            var f = c.getDeclaredField(field);
            f.setAccessible(true);
            Object v = f.get(null);
            if (v instanceof Map<?,?> m) m.clear();
            else if (v instanceof Collection<?> col) col.clear();
        } catch (Throwable ignored) {}
    }

    private static void clearField(Class<?> owner, String field, Object instance) {
        try {
            var f = owner.getDeclaredField(field);
            f.setAccessible(true);
            Object v = f.get(instance);
            if (v instanceof Map<?,?> m) m.clear();
            else if (v instanceof Collection<?> col) col.clear();
        } catch (Throwable ignored) {}
    }

    private static void truncateFile(Path path) {
        try {
            if (!Files.exists(path)) return;
            try (RandomAccessFile raf = new RandomAccessFile(path.toFile(), LT.L35)) {
                raf.setLength(0);
            }
        } catch (Throwable ignored) {}
    }


