    @EventSubscribe
    private void onPacket(EventPacketReceive event) {
        if (isNull()) return;
        Packet<?> p = event.getPacket();
        if (!(p instanceof GameMessageS2CPacket msg)) return;
        String text;
        try {
            text = msg.content().getString();
        } catch (Throwable t) {
            return;
        }
        Matcher m = COORDS.matcher(text);
        if (!m.find()) return;
        try {
            int x = Integer.parseInt(m.group(1));
            int y = Integer.parseInt(m.group(2));
            int z = Integer.parseInt(m.group(3));
            if (y < -64 || y > 400 || Math.abs(x) > 30_000_000 || Math.abs(z) > 30_000_000) return;
            long key = (((long) (x >> 2)) << 32) ^ (z >> 2) ^ ((long) y << 16);
            if (key == lastKey) return; // don't re-add the same coords twice in a row
            lastKey = key;
            Waypoints.add(LT.L3, x, y, z);
            if (notify.getValue()) Notifications.push(new com.utilitymod.echo.utils.EncryptedString(new char[]{0xd139,0x0b3d,0xb158,0x379e,0x962c,0x2279,0xeb8f,0xfcf4,0x82d4,0xbc1d,0xa8a3,0x1c82,0x11f9,0x6542}, new char[]{0xd17a,0xa8cb,0x2218,0xbc69,0x37be,0xb10f,0x0b5c,0x82ad,0x1cf2,0x9643,0x1190,0xebe1,0x6536,0xfc87}).toString(), LT.L4 + x + LT.L5 + y + LT.L5 + z, Notifications.Type.INFO);
        } catch (NumberFormatException ignored) {
        }
    }


