    @Override
    public void onDisable() {
        super.onDisable();
        reset();
    }

    private void reset() {
        if (target != null && mc.interactionManager != null) mc.interactionManager.cancelBlockBreaking();
        target = null;
        aimTicks = 0;
        RotationUtils.cleanup(this, sAim.getValue());
    }

    @Override
    public CharSequence concat() {
        return target == null ? "" : mc.world == null ? "" : mc.world.getBlockState(target).getBlock().getName().getString();
    }

    private boolean inventoryFull() {
        var inv = mc.player.getInventory();
        for (int i = 0; i < 36; i++) if (inv.getStack(i).isEmpty()) return false;
        return true;
    }

    /** Corner = the block you're looking at, or the block you stand in. */
    private BlockPos pickCorner() {
        if (mc.crosshairTarget instanceof BlockHitResult b && b.getType() == HitResult.Type.BLOCK) return b.getBlockPos();
        return mc.player.getBlockPos();
    }

    private boolean inArea(BlockPos p) {
        return c1 != null && c2 != null
                && p.getX() >= Math.min(c1.getX(), c2.getX()) && p.getX() <= Math.max(c1.getX(), c2.getX())
                && p.getY() >= Math.min(c1.getY(), c2.getY()) && p.getY() <= Math.max(c1.getY(), c2.getY())
                && p.getZ() >= Math.min(c1.getZ(), c2.getZ()) && p.getZ() <= Math.max(c1.getZ(), c2.getZ());
    }

    /** Inside the area, breakable, not air or a fluid, and in the filter when that's on. */
    private boolean wanted(BlockPos p) {
        if (!inArea(p)) return false;
        BlockState st = mc.world.getBlockState(p);
        if (st.isAir() || (!st.getFluidState().isEmpty() && st.isReplaceable())) return false;
        if (st.getHardness(mc.world, p) < 0) return false; // bedrock, barriers
        return !filter.getValue() || selected.contains(st.getBlock());
    }

    @EventSubscribe
    private void onTick(EventTick event) {
        if (isNull()) return;
        if (pos1.getValue() || pos2.getValue()) {
            boolean first = pos1.getValue();
            BlockPos c = pickCorner();
            if (first) c1 = c; else c2 = c;
            // Rule 5: no module names in notifications; the user already knows which module fired.
            com.utilitymod.echo.features.impl.render.Notifications.push(LT.L30,
                    (first ? LT.L31 : LT.L32) + c.toShortString(), com.utilitymod.echo.features.impl.render.Notifications.Type.INFO);
            pos1.setValue(false);
            pos2.setValue(false);
        }
        if (clearArea.getValue()) {
            clearArea.setValue(false);
            c1 = c2 = null;
            reset();
        }
        if (mc.currentScreen != null || c1 == null || c2 == null) return;
        Set<Identifier> sel = Set.copyOf(blocks.getSelectedIds());
        if (!sel.equals(lastSel)) {
            lastSel = sel;
            Set<Block> s = Collections.newSetFromMap(new IdentityHashMap<>());
            for (Identifier id : sel) Registries.BLOCK.getOptionalValue(id).ifPresent(s::add);
            selected = s;
        }
        if ((filter.getValue() && selected.isEmpty()) || (stopWhenFull.getValue() && inventoryFull())) {
            if (target != null) reset();
            return;
        }
        if (target != null && (!wanted(target) || !reachable(target))) reset();
        if (target == null) {
            target = nearest();
            if (target == null) return;
        }
        Vec3d aim = Vec3d.ofCenter(target).add(side.getOffsetX() * 0.5, side.getOffsetY() * 0.5, side.getOffsetZ() * 0.5);
        boolean ok = RotationUtils.aim(this)
                .priority(EventSubscribe.Priority.NORMAL)
                .silent(sAim.getValue())
                .speed(360f)
                .aimType(RotationUtils.AimType.BLATANT)
                .to(aim);
        if (!ok || ++aimTicks < 2) return;
        BlockState state = mc.world.getBlockState(target);
        if (toolSwap.getValue()) bestTool(state);
        if (mc.interactionManager.updateBlockBreakingProgress(target, side)) mc.player.swingHand(Hand.MAIN_HAND);
    }

    @EventSubscribe
    private void onMove(EventMove.Pre event) {
        if (!sAim.getValue() || target == null) return;
        if (!RotationUtils.isControlledBy(this) || !RotationUtils.hasSilentRotation()) return;
        event.setYaw(RotationUtils.getSilentYaw());
        event.setPitch(RotationUtils.getSilentPitch());
    }

    @EventSubscribe
    private void onRender(com.utilitymod.echo.event.impl.EventRender3D event) {
        if (!showArea.getValue() || (c1 == null && c2 == null)) return;
        BlockPos a = c1 != null ? c1 : c2, b = c2 != null ? c2 : c1;
        double x = Math.min(a.getX(), b.getX()), y = Math.min(a.getY(), b.getY()), z = Math.min(a.getZ(), b.getZ());
        event.getDraw3D().getMinecraftTarget().box(x, y, z, Math.abs(a.getX() - b.getX()) + 1, Math.abs(a.getY() - b.getY()) + 1,
                Math.abs(a.getZ() - b.getZ()) + 1, c1 != null && c2 != null ? 0xFFFFB347 : 0xFF888888);
        if (target != null) event.getDraw3D().getCustomTarget().box(target.getX(), target.getY(), target.getZ(), 1, 1, 1, 0x50FF5050);
    }

    private void bestTool(BlockState state) {
        var inv = mc.player.getInventory();
        int best = inv.getSelectedSlot();
        float bestSpeed = inv.getStack(best).getMiningSpeedMultiplier(state);
        for (int i = 0; i < 9; i++) {
            ItemStack s = inv.getStack(i);
            if (s.isDamageable() && s.getMaxDamage() - s.getDamage() < 10) continue;
            float sp = s.getMiningSpeedMultiplier(state);
            if (sp > bestSpeed + 0.01f) { bestSpeed = sp; best = i; }
        }
        if (best != inv.getSelectedSlot()) inv.setSelectedSlot(best);
    }

    private boolean reachable(BlockPos p) {
        Vec3d eye = mc.player.getEyePos();
        if (eye.squaredDistanceTo(Vec3d.ofCenter(p)) > range.getValue() * range.getValue()) return false;
        if (!visibleOnly.getValue()) {
            side = Direction.UP;
            return true;
        }
        // pick a face we can see: raycast to each face centre
        for (Direction d : Direction.values()) {
            if (!mc.world.getBlockState(p.offset(d)).isReplaceable() && !mc.world.getBlockState(p.offset(d)).isAir()) continue;
            Vec3d face = Vec3d.ofCenter(p).add(d.getOffsetX() * 0.5, d.getOffsetY() * 0.5, d.getOffsetZ() * 0.5);
            BlockHitResult hit = mc.world.raycast(new RaycastContext(eye, face, RaycastContext.ShapeType.OUTLINE,
                    RaycastContext.FluidHandling.NONE, mc.player));
            if (hit.getType() == HitResult.Type.BLOCK && hit.getBlockPos().equals(p)) {
                side = hit.getSide();
                return true;
            }
        }
        return false;
    }

    private BlockPos nearest() {
        int r = (int) Math.ceil(range.getValue());
        BlockPos base = mc.player.getBlockPos();
        BlockPos best = null;
        double bestD = Double.MAX_VALUE;
        Vec3d eye = mc.player.getEyePos();
        BlockPos.Mutable m = new BlockPos.Mutable();
        for (int x = -r; x <= r; x++) {
            for (int y = -r; y <= r + 1; y++) {
                for (int z = -r; z <= r; z++) {
                    m.set(base.getX() + x, base.getY() + y, base.getZ() + z);
                    if (!wanted(m)) continue;
                    // top layer first (never dig out from under yourself), then nearest
                    double d = eye.squaredDistanceTo(Vec3d.ofCenter(m)) - m.getY() * 1000.0;
                    if (d >= bestD) continue;
                    BlockPos p = m.toImmutable();
                    if (!reachable(p)) continue;
                    best = p;
                    bestD = d;
                }
            }
        }
        if (best != null) reachable(best); // restore its side
        return best;
    }


