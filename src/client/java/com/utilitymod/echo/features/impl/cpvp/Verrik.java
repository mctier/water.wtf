    private boolean offhandTotem() { return mc.player.getOffHandStack().isOf(Items.TOTEM_OF_UNDYING); }

    private int totems() {
        int n = 0;
        var inv = mc.player.getInventory();
        for (int i = 0; i < 36; i++) if (inv.getStack(i).isOf(Items.TOTEM_OF_UNDYING)) n += inv.getStack(i).getCount();
        return n;
    }

    @EventSubscribe
    @SuppressWarnings("unused")
    private void onTick(EventTick e) {
        if (isNull()) return;
        if (mc.player.getHealth() < lastHealth) lastHurt = System.currentTimeMillis();
        lastHealth = mc.player.getHealth();
        if (waitShield.getValue() && mc.player.isBlocking()) return;
        if (mode.is(new EncryptedString(new char[]{0x2248, 0xa886, 0xd129}, new char[]{0xd17a, 0xa8cb, 0x2218}))) { smp(); return; }
        crystal();
    }

    // ---- SMP ----------------------------------------------------------------------------

    private void smp() {
        if (offhandTotem() || System.currentTimeMillis() < readyAt) return;
        boolean low = mc.player.getHealth() + mc.player.getAbsorptionAmount() <= health.getValue();
        if (!low && !(antiMace.getValue() && maceDive())) return;
        int src = Cpvp.findInventory(Items.TOTEM_OF_UNDYING, true);
        if (src < 0) return;
        Cpvp.swapInto(src, 40);
        readyAt = Cpvp.next(delay);
    }

    /** An enemy above you, falling, holding a mace and close enough to land on you. */
    private boolean maceDive() {
        for (PlayerEntity p : mc.world.getPlayers()) {
            if (p == mc.player || !p.isAlive()) continue;
            if (!(p.getMainHandStack().getItem() instanceof MaceItem)) continue;
            double dy = p.getY() - mc.player.getY();
            double h = Math.hypot(p.getX() - mc.player.getX(), p.getZ() - mc.player.getZ());
            if (dy > 1.5 && h < 4 + dy * .25 && p.getVelocity().y < -0.3) return true;
        }
        return false;
    }

