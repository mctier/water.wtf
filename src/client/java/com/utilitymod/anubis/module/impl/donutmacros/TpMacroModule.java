   @Override
   public boolean persistEnabled() {
      return false;
   }

   @Override
   protected void onEnable() {
      String name = this.target.get().trim();
      if (!VALID_NAME.matcher(name).matches()) {
         ModuleChat.send(this, ModuleChat.body().warn(LT.L15));
         this.requestDisable();
      } else {
         this.confirm.reset();
         this.holdUntil = 0L;
         this.nextAt = 0L;
         this.sent = 0;
         ModuleChat.send(
            this,
            ModuleChat.body().text(LT.L16).value(LT2.L1 + this.command.get() + " " + name).text(LT.L17).value(this.interval.formatted() + LT2.L2).text(LT2.L3)
         );
      }
   }

   @Override
   protected void onDisable() {
      if (this.sent > 0) {
         ModuleChat.send(this, ModuleChat.body().text(LT.L18).value(this.sent).text(this.sent == 1 ? LT.L19 : LT.L20));
      }
   }

   @EventHandler
   public void onPacket(PacketReceiveNettyEvent event) {
      if (event.packet instanceof GameMessageS2CPacket chat && chat.content() != null) {
         Matcher wait = RATE_LIMIT.matcher(ServerText.normalize(chat.content().getString()));
         if (wait.find()) {
            try {
               this.holdUntil = System.currentTimeMillis() + (long)Math.ceil(Double.parseDouble(wait.group(1)) * 1000.0) + 80L;
            } catch (NumberFormatException var5) {
            }
         }
      }
   }

   @EventHandler
   public void onTick(TickEvent event) {
      MinecraftClient mc = MinecraftClient.getInstance();
      ClientPlayerEntity player = mc.player;
      if (player != null && mc.getNetworkHandler() != null && !player.isDead()) {
         this.confirm.tick(mc);
         long now = System.currentTimeMillis();
         if (now >= this.nextAt && now >= this.holdUntil) {
            player.networkHandler.sendChatCommand(this.command.get() + " " + this.target.get().trim());
            this.sent++;
            this.nextAt = now + (long)(this.interval.get() * 1000.0F);
         }
      }
   }


