    @Override
    public void onDisable() {
        super.onDisable();
        seen.clear();
    }

    @EventSubscribe
    private void onTick(EventTick event) {
        if (isNull()) {
            seen.clear();
            return;
        }
        Set<UUID> now = new HashSet<>();
        for (PlayerEntity p : mc.world.getPlayers()) {
            if (p == mc.player || (ignoreFriends.getValue() && TargetUtils.isFriend(p))) continue;
            now.add(p.getUuid());
            if (seen.putIfAbsent(p.getUuid(), p.getName().getString()) == null) {
                Notifications.push(new com.utilitymod.echo.utils.EncryptedString(new char[]{0xeb84,0x0b7c,0x1c93,0x962d,0x226b,0xd12c,0x11f7,0x82ff,0xa8a2,0x37df,0xb163,0xbc1c}, new char[]{0xd17a,0xa8cb,0x2218,0xbc69,0x37be,0xb10f,0x0b5c,0x82ad,0x1cf2,0x9643,0x1190,0xebe1}).toString(), p.getName().getString() + LT.L4 + Math.round(mc.player.distanceTo(p)) + LT.L5, Notifications.Type.INFO);
                if (sound.getValue()) mc.player.playSound(SoundEvents.BLOCK_NOTE_BLOCK_PLING.value(), 0.6f, 1.8f);
            }
        }
        var it = seen.entrySet().iterator();
        while (it.hasNext()) {
            var e = it.next();
            if (now.contains(e.getKey())) continue;
            if (leave.getValue()) Notifications.push(new com.utilitymod.echo.utils.EncryptedString(new char[]{0xeb84,0x0b7c,0x1c93,0x962d,0x226b,0xd12c,0x11f7,0x82ff,0xa8a2,0x37df,0xb163,0xbc1c}, new char[]{0xd17a,0xa8cb,0x2218,0xbc69,0x37be,0xb10f,0x0b5c,0x82ad,0x1cf2,0x9643,0x1190,0xebe1}).toString(), e.getValue() + LT.L6, Notifications.Type.DISABLED);
            it.remove();
        }
    }


