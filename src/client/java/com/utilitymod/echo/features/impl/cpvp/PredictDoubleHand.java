    @Override
    public void onDisable() {
        super.onDisable();
        back();
        knownObsidian.clear();
    }

    @EventSubscribe
    @SuppressWarnings("unused")
    private void onTick(EventTick e) {
        if (isNull() || mc.currentScreen != null) return;
        if (paused()) { back(); return; }
        boolean threat = threat();
        int totem = Cpvp.hotbar(Items.TOTEM_OF_UNDYING);
        if (threat && totem >= 0) {
            if (home < 0 && Cpvp.selected() != totem) home = Cpvp.selected();
            mc.player.getInventory().setSelectedSlot(totem);
            clearAt = 0;
        } else if (home >= 0) {
            if (clearAt == 0) clearAt = Cpvp.next(reswapDelay);
            if (System.currentTimeMillis() >= clearAt) back();
        }
    }

    private void back() {
        if (home >= 0 && mc.player != null) mc.player.getInventory().setSelectedSlot(home);
        home = -1;
        clearAt = 0;
    }

    private boolean paused() {
        if (pause.isEnabled(new EncryptedString(new char[]{0xa8a3, 0xb16b, 0xd129, 0x2271, 0x37d2, 0xbc0c}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f})) && mc.player.isBlocking()) return true;
        if (pause.isEnabled(new EncryptedString(new char[]{0xa8a3, 0x9628, 0x82cc, 0x37da, 0x0b14, 0x1c91, 0x2279, 0xb12f, 0xd129, 0xbc1b}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad, 0x1cf2, 0x9643})) && on(new EncryptedString(new char[]{0xa8a3, 0x9628, 0x82cc, 0x37da, 0x0b14, 0x1c91, 0x2279, 0xb12f, 0xd129, 0xbc1b}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad, 0x1cf2, 0x9643}))) return true;
        return pause.isEnabled(new EncryptedString(new char[]{0x0b0e, 0x1c95, 0x82c4, 0x37da, 0xbc1b, 0xa8a3, 0xb12f, 0x2279, 0xd129}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad, 0x1cf2})) && on(new EncryptedString(new char[]{0x0b0e, 0x1c95, 0x82c4, 0x37da, 0xbc1b, 0xa8a3, 0xb12f, 0x2279, 0xd129}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad, 0x1cf2}));
    }

    private static boolean on(CharSequence name) {
        Module m = ModuleManager.get(String.valueOf(name));
        return m != null && m.isEnabled();
    }

    private boolean threat() {
        float s = sensitivity.getValue();
        float hp = mc.player.getHealth() + mc.player.getAbsorptionAmount();
        BlockPos me = mc.player.getBlockPos();
        if (triggers.isEnabled(new EncryptedString(new char[]{0x0b2f, 0xd13b, 0x37d1, 0xb17d, 0xbc01, 0x227b, 0xa8a5}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c}))) {
            for (BlockPos p : BlockPos.iterate(me.add(-4, -2, -4), me.add(4, 3, 4))) {
                if (Cpvp.charges(p) > 0 && Cpvp.damage(mc.player, p) * s >= hp * .6f) return true;
            }
        }
        if (triggers.isEnabled(new EncryptedString(new char[]{0x226b, 0xd135, 0xb166, 0x0b3d, 0xbc00, 0x37da, 0xa8a9, 0x82c3}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad}))) {
            Set<BlockPos> now = new HashSet<>();
            boolean fresh = false;
            for (BlockPos p : BlockPos.iterate(me.add(-2, -1, -2), me.add(2, 1, 2))) {
                if (!mc.world.getBlockState(p).isOf(Blocks.OBSIDIAN)) continue;
                BlockPos ip = p.toImmutable();
                now.add(ip);
                if (!knownObsidian.isEmpty() && !knownObsidian.contains(ip) && Cpvp.nearestEnemy(6 * s) != null) fresh = true;
            }
            knownObsidian.clear();
            knownObsidian.addAll(now);
            if (fresh) return true;
        }
        for (Entity en : mc.world.getEntities()) {
            if (triggers.isEnabled(new EncryptedString(new char[]{0x2261, 0xd139, 0xb16e, 0x0b30, 0xbc1a, 0x37ca, 0xa8b9, 0x82de}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad})) && en instanceof EndCrystalEntity
                    && en.squaredDistanceTo(mc.player) < 36 * s * s) return true;
            if (triggers.isEnabled(new EncryptedString(new char[]{0x2279, 0xd12a, 0x37d2, 0xa8ae, 0xbc1b}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be})) && en instanceof EnderPearlEntity pearl
                    && pearl.getOwner() instanceof PlayerEntity owner && owner != mc.player
                    && pearl.squaredDistanceTo(mc.player) < 64 * s * s) return true;
        }
        for (PlayerEntity p : mc.world.getPlayers()) {
            if (p == mc.player || !p.isAlive()) continue;
            double d = p.distanceTo(mc.player);
            if (triggers.isEnabled(new EncryptedString(new char[]{0x0b0c, 0x1c82, 0x82c2, 0x37da, 0xbc1b, 0xa8bc, 0xb12f, 0x2277, 0xd129}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad, 0x1cf2})) && d < 4.5 * s && p.getMainHandStack().isIn(ItemTags.SWORDS)
                    && hp <= 8 * s) return true;
            if (triggers.isEnabled(new EncryptedString(new char[]{0x227b, 0xa8aa, 0xd137, 0xbc0c}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69})) && p.getMainHandStack().getItem() instanceof MaceItem
                    && p.getY() - mc.player.getY() > 1.5 && p.getVelocity().y < -0.3
                    && Math.hypot(p.getX() - mc.player.getX(), p.getZ() - mc.player.getZ()) < 5 * s) return true;
        }
        return false;
    }
