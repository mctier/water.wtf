    @Override
    public void onDisable() {
        super.onDisable();
        covered.clear();
        noticed.clear();
    }

    @EventSubscribe
    @SuppressWarnings("unused")
    private void onInput(EventHandleInput.Early e) {
        if (isNull() || mc.currentScreen != null) return;
        covered.keySet().removeIf(p -> !Cpvp.isAnchor(p));
        noticed.keySet().removeIf(p -> !Cpvp.isAnchor(p));
        if (System.currentTimeMillis() < readyAt) return;

        BlockPos me = mc.player.getBlockPos();
        for (BlockPos p : BlockPos.iterate(me.add(-5, -3, -5), me.add(5, 4, 5))) {
            if (!Cpvp.isAnchor(p) || !Cpvp.inReach(p)) continue;
            BlockPos a = p.toImmutable();
            boolean mine = Cpvp.own(a);
            if (mode.is(new EncryptedString(new char[]{0x227f, 0xd136, 0x37ca, 0xa8ae, 0xbc00}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be})) && !mine) continue;
            if (onlyOwn.getValue() && !mine) continue;
            if (covered.getOrDefault(a, 0) >= limit.getValue()) continue;
            int charges = Cpvp.charges(a);
            if (when.is(new EncryptedString(new char[]{0x227e, 0x9622, 0x11e2, 0xeb86, 0x82ee, 0x0b7c, 0xa8ae, 0xbc06, 0x1c9a, 0xd138, 0x37cc, 0x6553, 0xb16a}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c, 0x82ad, 0x1cf2, 0x9643, 0x1190, 0xebe1, 0x6536})) ? charges != 0 : charges == 0) continue;
            float dmg = Cpvp.damage(mc.player, a);
            if (dmg < minDamage.getValue()) continue;
            // reaction delay from the moment we first see the anchor
            long seen = noticed.computeIfAbsent(a, k -> Cpvp.next(delay));
            if (System.currentTimeMillis() < seen) continue;
            if (cover(a)) return;
        }
    }

    private boolean cover(BlockPos anchor) {
        BlockPos c = Cpvp.coverPos(anchor);
        int slot = Cpvp.hotbar(Cpvp.coverItem(block.getValue()));
        if (c == null || slot < 0) return false;
        int home = Cpvp.selected();
        if (swap.is(new EncryptedString(new char[]{0x2276, 0xa8a4, 0xd134, 0xbc0c}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69})) && home != slot) return false;
        Cpvp.select(slot, swap.getValue());
        var support = com.utilitymod.echo.utils.blocks.BlockUtils.findPlacementHit(c, false);
        if (support == null) return false;
        boolean silent = mode.is(new EncryptedString(new char[]{0x0b28, 0xd138, 0x37df, 0xb161, 0xbc1d, 0x2279, 0xa8a7}, new char[]{0xd17a, 0xa8cb, 0x2218, 0xbc69, 0x37be, 0xb10f, 0x0b5c}));
        if (!Cpvp.aimed(this, silent, fov.getValue(), support.hitResult().getPos(), support.hitResult().getBlockPos())) return true;
        boolean ok = Cpvp.place(c);
        if (home != slot) Cpvp.restore(home, swap.getValue());
        if (ok) {
            covered.merge(anchor, 1, Integer::sum);
            // stop covering once the blast left over is acceptable
            if (Cpvp.damage(mc.player, anchor) <= maxDamage.getValue()) covered.put(anchor, limit.getValue());
        }
        readyAt = Cpvp.next(delay);
        return true;
    }
